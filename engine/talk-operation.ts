const TALK_WIRE_NAMES: Record<string, string> = {
  "25": "SEND_MESSAGE",
  "26": "RECEIVE_MESSAGE",
  "50": "NOTIFIED_RECEIVED_CALL",
  "51": "CANCEL_CALL",
  "55": "NOTIFIED_READ_MESSAGE",
  "64": "DESTROY_MESSAGE",
  "65": "NOTIFIED_DESTROY_MESSAGE",
  "139": "SEND_REACTION",
  "140": "NOTIFIED_SEND_REACTION",
  "154": "NOTIFIED_GCS_REACTION",
  "158": "EDIT_MESSAGE",
  "159": "NOTIFIED_EDIT_MESSAGE",
  // LINE Android 26.11.0 wire mapping. LINEJS 3.4.2 generated types are
  // shifted in this range (scheduled-message vs service-chat operations).
  "160": "UPDATE_SERVICE_CHAT",
  "161": "MARK_SERVICE_CHAT_AS_READ",
  "162": "UPDATE_SERVICE_CHAT_NOTIFICATION_TEXT",
  "163": "ADD_SCHEDULED_MESSAGE",
  "164": "UPDATE_SCHEDULED_MESSAGE",
  "165": "DELETE_SCHEDULED_MESSAGE",
  "166": "E2EE_REENCRYPT_SCHEDULED_MESSAGE",
  "167": "SEND_FAILED_SCHEDULED_MESSAGE",
  "168": "SEND_SUCCEEDED_SCHEDULED_MESSAGE",
  "169": "LINE_AUTH_NOTIFICATION",
};

const LINEJS_342_SHIFTED_NAMES: Record<string, string> = {
  ADD_SCHEDULED_MESSAGE: "UPDATE_SERVICE_CHAT",
  UPDATE_SCHEDULED_MESSAGE: "MARK_SERVICE_CHAT_AS_READ",
  DELETE_SCHEDULED_MESSAGE: "UPDATE_SERVICE_CHAT_NOTIFICATION_TEXT",
  E2EE_REENCRYPT_SCHEDULED_MESSAGE: "ADD_SCHEDULED_MESSAGE",
  SEND_FAILED_SCHEDULED_MESSAGE: "UPDATE_SCHEDULED_MESSAGE",
  SEND_SUCCEEDED_SCHEDULED_MESSAGE: "DELETE_SCHEDULED_MESSAGE",
  UPDATE_SERVICE_CHAT: "E2EE_REENCRYPT_SCHEDULED_MESSAGE",
  MARK_SERVICE_CHAT_AS_READ: "SEND_FAILED_SCHEDULED_MESSAGE",
  UPDATE_SERVICE_CHAT_NOTIFICATION_TEXT: "SEND_SUCCEEDED_SCHEDULED_MESSAGE",
  LINE_AUTH_NOTIFICATION: "LINE_AUTH_NOTIFICATION",
};

export function canonicalTalkOperationType(value: unknown, linejsVersion: string): string {
  const text = String(value ?? "").trim();
  if (!text) return "";
  if (TALK_WIRE_NAMES[text]) return TALK_WIRE_NAMES[text];
  const upper = text.toUpperCase();
  if (linejsVersion === "3.4.2") return LINEJS_342_SHIFTED_NAMES[upper] ?? upper;
  return upper;
}

export function isLineServiceChatOperation(type: string): boolean {
  return [
    "UPDATE_SERVICE_CHAT",
    "MARK_SERVICE_CHAT_AS_READ",
    "UPDATE_SERVICE_CHAT_NOTIFICATION_TEXT",
    "LINE_AUTH_NOTIFICATION",
  ].includes(type);
}
