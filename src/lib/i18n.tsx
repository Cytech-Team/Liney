const LanguageContext = createContext<AppLanguage>("th");

export function translateText(
  language: AppLanguage,
  source: string,
  values: TranslationValues = {},
): string {
  const template = language === "en" ? ENGLISH_TRANSLATIONS[source] ?? source : source;
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function LanguageProvider({ language, children }: { language: AppLanguage; children: ReactNode }) {
  return <LanguageContext.Provider value={language}>{children}</LanguageContext.Provider>;
}

export function useAppTranslation() {
  const language = useContext(LanguageContext);
  const t = useCallback(
    (source: string, values?: TranslationValues) => translateText(language, source, values),
    [language],
  );
  return { language, english: language === "en", t };
}
