const LanguageContext = createContext<AppLanguage>("th");

export function translateText(
  language: AppLanguage,
  source: string,
  values: TranslationValues = {},
): string {
  const template =
    language === "en"
      ? ENGLISH_TRANSLATIONS[source] ?? source
      : language === "zh-TW"
        ? ZH_TW_TRANSLATIONS[source] ?? ENGLISH_TRANSLATIONS[source] ?? source
        : source;
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function translateDisplayText(language: AppLanguage, source: string): string {
  if (language === "th" || !source) return source;
  const direct = translateText(language, source);
  if (direct !== source) return direct;
  const ipcMatch = source.match(/^Error invoking remote method '[^']+':\s*(?:Error:\s*)?(.+)$/i);
  if (ipcMatch) {
    const inner = translateDisplayText(language, ipcMatch[1].trim());
    if (inner !== ipcMatch[1].trim()) return inner;
  }
  const openChatMatch = source.match(/^OpenChat · ([\d,]+) คน$/);
  if (openChatMatch) {
    return translateText(language, "OpenChat · {{count}} คน", { count: openChatMatch[1] });
  }
  const compositeMatch = source.match(
    /^(รูปภาพ|วิดีโอ|เสียง|ข้อความเสียง|ไฟล์|โทรสำเร็จ|ยกเลิกการโทร|ปฏิเสธสาย|ไม่มีการตอบรับ|การโทร|สร้างอัลบั้ม|เพิ่มรูปในอัลบั้ม|เพิ่มรูปภาพในอัลบั้ม|อัปเดตอัลบั้ม)( · |: )(.+)$/,
  );
  if (compositeMatch) {
    const [, prefix, separator, rawRest] = compositeMatch;
    let rest = rawRest;
    const minSec = rawRest.match(/^(\d+) นาที (\d+) วินาที$/);
    const minOnly = rawRest.match(/^(\d+) นาที$/);
    const secOnly = rawRest.match(/^(\d+) วินาที$/);
    if (minSec) {
      rest = translateText(language, "{{minutes}} นาที {{seconds}} วินาที", { minutes: minSec[1], seconds: minSec[2] });
    } else if (minOnly) {
      rest = translateText(language, "{{minutes}} นาที", { minutes: minOnly[1] });
    } else if (secOnly) {
      rest = translateText(language, "{{seconds}} วินาที", { seconds: secOnly[1] });
    } else {
      rest = translateDisplayText(language, rawRest);
    }
    return `${translateText(language, prefix)}${separator}${rest}`;
  }
  return source;
}

export function LanguageProvider({ language, children }: { language: AppLanguage; children: ReactNode }) {
  return <LanguageContext.Provider value={language}>{children}</LanguageContext.Provider>;
}

export function useAppTranslation() {
  const language = useContext(LanguageContext);
  const t = useCallback(
    (source: string, values?: TranslationValues) => translateText(language, source, values),
    [language],
  );
  const td = useCallback(
    (source: string) => translateDisplayText(language, source),
    [language],
  );
  return { language, english: language === "en", locale: getLocaleTag(language), t, td };
}
